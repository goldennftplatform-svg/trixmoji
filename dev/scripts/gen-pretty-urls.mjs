import fs from 'fs';
import path from 'path';

const root = path.resolve('C:/Users/franc/Desktop/DOSWAPZ');

function walk(dir, acc = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name === 'node_modules' || ent.name.startsWith('.')) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, acc);
    else if (ent.isFile() && ent.name.endsWith('.html')) acc.push(p);
  }
  return acc;
}

function rels(base) {
  return walk(path.join(root, base)).map((f) =>
    path.relative(path.join(root, base), f).split(path.sep).join('/')
  );
}

function slug(rel) {
  return rel.replace(/\/index\.html$/i, '').replace(/\.html$/i, '').replace(/\/$/, '');
}

function fileToPretty(filePath) {
  const p = String(filePath).split('?')[0].split('#')[0];
  if (p === '/classic/hub.html' || p === '/classic/hub' || p === '/hub.html' || p === '/hub') return '/past';
  if (p === '/orbit/hub.html' || p === '/orbit/hub') return '/present';
  if (p === '/future/hub.html' || p === '/future/hub') return '/future';
  if (p === '/harbinger.html') return '/harbinger/past';
  const m = p.match(/^\/(classic|orbit)\/pages\/(.+)$/);
  if (!m) return null;
  const era = m[1] === 'orbit' ? 'present' : 'past';
  const rest = slug(m[2]);
  if (!rest) return null;
  return '/' + rest + '/' + era;
}

const classic = rels('classic/pages');
const orbit = rels('orbit/pages');

const lines = [
  '# Pretty era URLs. Generated by dev/scripts/gen-pretty-urls.mjs',
  '# Address bar stays /name/past or /name/present (200 rewrite to files).',
  '/past  /classic/hub.html  200',
  '/present  /orbit/hub.html  200',
  '/future  /future/hub.html  200'
];

for (const r of classic) {
  lines.push('/' + slug(r) + '/past  /classic/pages/' + r + '  200');
}
for (const r of orbit) {
  lines.push('/' + slug(r) + '/present  /orbit/pages/' + r + '  200');
}

fs.writeFileSync(path.join(root, '_redirects'), lines.join('\n') + '\n', 'utf8');
console.log('Wrote _redirects (' + (lines.length - 3) + ' rules)');

function rewriteHub(file) {
  let s = fs.readFileSync(file, 'utf8');
  const orig = s;
  s = s.replace(/(["'])(\/(?:classic|orbit)\/(?:hub\.html|pages\/[^"'?#]+))(\?[^"'#]*)?(#[^"']*)?\1/g, function (_, q, p, qs, hash) {
    const pretty = fileToPretty(p);
    if (!pretty) return q + p + (qs || '') + (hash || '') + q;
    return q + pretty + (qs || '') + (hash || '') + q;
  });
  s = s.replace(/https:\/\/doswapz\.com\/classic\/hub\.html/g, 'https://doswapz.com/past');
  s = s.replace(/https:\/\/doswapz\.com\/orbit\/hub\.html/g, 'https://doswapz.com/present');
  if (s !== orig) {
    fs.writeFileSync(file, s, 'utf8');
    console.log('Updated ' + path.relative(root, file));
  } else {
    console.log('No href changes in ' + path.relative(root, file));
  }
}

rewriteHub(path.join(root, 'classic/hub.html'));
rewriteHub(path.join(root, 'orbit/hub.html'));
rewriteHub(path.join(root, 'future/hub.html'));
